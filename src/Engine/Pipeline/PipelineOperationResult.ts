import type { Story } from '../../Contracts/Domain/Story/Story.js';
import type { IOMessageOutbound } from '../../Contracts/IOChannel/IOMessageOutbound.js';

/**
 * Represents the result of a pipeline operation, including any changes that should be added to the DB or sent to the user.
 */
export interface PipelineOperationResult {
    /** Indicates whether the pipeline should stop processing further operations. */
    readonly stopProcessing: boolean;
    /** Optional changes to the story resulting from the operation. */
    readonly storyChanges?: Readonly<Partial<Story>>;
    /** Optional new messages generated by the operation. */
    readonly newMessages?: readonly Readonly<IOMessageOutbound>[];
}
